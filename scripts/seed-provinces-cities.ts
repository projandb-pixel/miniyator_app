async function seedProvincesAndCities() {
  try {
    console.log("شروع پر کردن دیتابیس با استان‌ها و شهرها...");

    // حذف داده‌های قبلی
    console.log("حذف داده‌های قبلی...");
    await prisma.cities.deleteMany({});
    await prisma.provinces.deleteMany({});
    console.log("داده‌های قبلی حذف شدند.");

    // افزودن استان‌ها و شهرها
    for (const [provinceName, cities] of Object.entries(
      iranProvincesAndCities
    )) {
      const provinceId = randomUUID();
      
      // افزودن استان
      await prisma.provinces.create({
        data: {
          id: provinceId,
          name: provinceName,
        },
      });
      console.log(`✓ استان ${provinceName} اضافه شد`);

      // افزودن شهرهای این استان
      for (const cityName of cities) {
        const cityId = randomUUID();
        try {
          await prisma.cities.upsert({
            where: {
              provinceId_name: {
                provinceId: provinceId,
                name: cityName,
              },
            },
            update: {
              name: cityName,
            },
            create: {
              id: cityId,
              name: cityName,
              provinceId: provinceId,
            },
          });
        } catch (error: any) {
          // اگر upsert کار نکرد، از create استفاده کن
          if (error.code !== 'P2002') {
            console.error(`خطا در افزودن شهر ${cityName}:`, error.message);
          }
        }
      }
      console.log(`  ✓ ${cities.length} شهر برای ${provinceName} اضافه شد`);
    }

    console.log("\n✅ پر کردن دیتابیس با موفقیت انجام شد!");
    
    // نمایش آمار
    const provinceCount = await prisma.provinces.count();
    const cityCount = await prisma.cities.count();
    console.log(`\n📊 آمار:`);
    console.log(`  - تعداد استان‌ها: ${provinceCount}`);
    console.log(`  - تعداد شهرها: ${cityCount}`);
  } catch (error) {
    console.error("❌ خطا در پر کردن دیتابیس:", error);
    throw error;
  } finally {
    await prisma.$disconnect();
  }
}

// اجرای اسکریپت
seedProvincesAndCities()
  .then(() => {
    console.log("\n✅ اسکریپت با موفقیت اجرا شد!");
    process.exit(0);
  })
  .catch((error) => {
    console.error("\n❌ خطا در اجرای اسکریپت:", error);
    process.exit(1);
  });

