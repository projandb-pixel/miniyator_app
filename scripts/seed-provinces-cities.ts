// Parse connection string (same as lib/prisma.ts)
function parseConnectionString(connectionString: string) {
  // Remove sqlserver:// prefix
  const url = connectionString.replace(/^sqlserver:\/\//, '')
  
  // Split host:port and parameters
  const [hostPort, ...params] = url.split(';')
  const [server, portStr] = hostPort.split(':')
  const port = portStr ? Number.parseInt(portStr, 10) : 1433
  
  // Parse parameters
  const config: {
    server: string
    port: number
    database?: string
    user?: string
    password?: string
    options?: {
      encrypt?: boolean
      trustServerCertificate?: boolean
    }
  } = {
    server,
    port,
    options: {},
  }
  
  for (const param of params) {
    const [key, value] = param.split('=')
    if (!key || !value) continue
    
    switch (key.toLowerCase()) {
      case 'database':
        config.database = value
        break
      case 'user':
        config.user = value
        break
      case 'password':
        config.password = value
        break
      case 'encrypt':
        config.options!.encrypt = value.toLowerCase() === 'true'
        break
      case 'trustservercertificate':
        config.options!.trustServerCertificate = value.toLowerCase() === 'true'
        break
    }
  }
  
  return config
}

